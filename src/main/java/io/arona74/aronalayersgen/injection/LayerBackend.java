package io.arona74.aronalayersgen.injection;

import io.arona74.aronalayersgen.AronaLayersGen;
import io.arona74.aronalayersgen.Compat;
import io.arona74.aronalayersgen.LayerConfig;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.RandomState;

import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Where a level's layer counts come from, worked out from that level's own chunk generator and
 * RandomState instead of from config. Detection is per level, so a TerraForged or Tellus
 * overworld still gets the vanilla backend in its Nether and End, and a flat or void world gets
 * nothing rather than counts read from a density field that does not describe its ground.
 *
 * <p>A dimension with a ceiling (the Nether, cave dimensions) gets nothing whatever its generator:
 * layers sit on the open surface, and there every column's top is bedrock roof.
 *
 * <p>Order matters: Tellus and TerraForged both drive a {@link NoiseBasedChunkGenerator} (or a
 * subclass), whose density field no longer describes the terrain they place, so they are checked
 * before the vanilla case.
 */
public enum LayerBackend {
    /** Tellus's EarthChunkGenerator: real-world elevation. */
    TELLUS,
    /** A dimension generated by FreeTerraForged or ReTerraForged: TerraForged cells. */
    TERRAFORGED,
    /** Any other noise generator (vanilla, amplified, datapack terrain): the density field. */
    VANILLA,
    /** Ceiling dimensions, flat, debug, void and other generators: no layers. */
    NONE;

    private static final Map<String, LayerBackend> ANNOUNCED = new ConcurrentHashMap<>();

    /** The backend for chunks of {@code level}, or NONE when layer injection is off. */
    public static LayerBackend of(ServerLevel level) {
        if (level == null) return NONE;
        return of(level, level.getChunkSource().getGenerator(), RandomStateHolder.noiseConfigFor(level));
    }

    /**
     * The backend for a chunk generated by {@code generator} with {@code randomState}, or NONE
     * when layer injection is off. {@code level} only names the dimension in the log.
     */
    public static LayerBackend of(ServerLevel level, ChunkGenerator generator, RandomState randomState) {
        if (!LayerConfig.LAYER_INJECTION) return NONE;
        LayerBackend backend = hasCeiling(level) ? NONE : detect(generator, randomState);
        if (level != null) announce(level, backend);
        return backend;
    }

    private static boolean hasCeiling(ServerLevel level) {
        return level != null && level.dimensionType().hasCeiling();
    }

    private static LayerBackend detect(ChunkGenerator generator, RandomState randomState) {
        if (TellusCompat.isTellusGenerator(generator)) return TELLUS;
        if (RTFCompat.flavor() != null) {
            if (RTFCompat.isTerraForgedDimension(randomState)) return TERRAFORGED;
            // Installed but not bound: this may well be a TerraForged dimension we cannot tell
            // apart, and its density field would yield fiction, so place nothing anywhere.
            if (!RTFCompat.isRTFAvailable()) return NONE;
        }
        if (generator instanceof NoiseBasedChunkGenerator) return VANILLA;
        return NONE;
    }

    /** Logs each dimension's backend once, and again if it ever changes. */
    private static void announce(ServerLevel level, LayerBackend backend) {
        String dimension = Compat.keyId(level.dimension());
        if (ANNOUNCED.put(dimension, backend) == backend) return;
        String source = switch (backend) {
            case TELLUS -> "Tellus elevation data";
            case TERRAFORGED -> RTFCompat.flavor().displayName() + " cells";
            case VANILLA -> "the vanilla density field";
            case NONE -> hasCeiling(level)
                    ? "nothing (the dimension has a ceiling)"
                    : RTFCompat.flavor() != null && !RTFCompat.isRTFAvailable()
                    ? "nothing (" + RTFCompat.flavor().displayName() + " is installed but could not be bound)"
                    : "nothing (" + level.getChunkSource().getGenerator().getClass().getSimpleName() + " is not supported)";
        };
        AronaLayersGen.LOGGER.info("[Layers] {}: layers from {}", dimension, source);
    }

    /** Forgets the logged backends; called when a world closes. */
    public static void clear() {
        ANNOUNCED.clear();
    }
}
